// Aggregates all lesson content for the seed.
//
// The A1/A2 base lives in the flat files next to this one (categories.js,
// words.js, ...) and is deliberately left untouched: the live database was
// provisioned from it, and the seed matches existing rows by natural key,
// so keeping that content byte-for-byte stable keeps every re-sync a no-op
// for it. Everything from B1 upwards lives in one module per level under
// levels/, each exporting the same shape:
//   { categories, grammarRules, words, grammarExercises, practicalSentences, readings }
// plus a per-level vocabulary pack under levels/vocab-<level>.js (frequency-
// based word lists, translated by hand; morphology from the Open Russian
// dictionary -- see SOURCES.md).
const path = require('path');
const fs = require('fs');

const base = {
  categories: require('./categories'),
  grammarRules: require('./grammarRules'),
  words: require('./words'),
  grammarExercises: require('./grammarExercises'),
  practicalSentences: require('./practicalSentences'),
  readings: []
};

const LEVEL_ORDER = ['a1', 'a2', 'b1', 'b2', 'c1', 'c2'];
const levelModules = LEVEL_ORDER.map((lvl) => {
  const file = path.join(__dirname, 'levels', `${lvl}.js`);
  const vocab = path.join(__dirname, 'levels', `vocab-${lvl}.js`);
  const mod = fs.existsSync(file) ? require(file) : {};
  const vocabMod = fs.existsSync(vocab) ? require(vocab) : {};
  return {
    categories: [...(mod.categories || []), ...(vocabMod.categories || [])],
    grammarRules: mod.grammarRules || [],
    words: [...(mod.words || []), ...(vocabMod.words || [])],
    grammarExercises: mod.grammarExercises || [],
    practicalSentences: (mod.practicalSentences || []).map((s) => ({ ...s, level: s.level || lvl.toUpperCase() })),
    readings: mod.readings || [],
    drills: mod.drills || null
  };
});

// Open Russian morphology (stress marks + forms) for every word the app uses,
// keyed by bare form. Generated by seed/import/build-openrussian.js.
let forms = {};
const formsFile = path.join(__dirname, 'generated', 'openrussian-forms.json');
if (fs.existsSync(formsFile)) forms = JSON.parse(fs.readFileSync(formsFile, 'utf8'));

function concat(key) {
  return [base[key], ...levelModules.map((m) => m[key])].flat();
}

const categories = concat('categories');
const seenSlugs = new Set();
for (const c of categories) {
  if (seenSlugs.has(c.slug)) throw new Error(`Duplicate category slug in seed data: ${c.slug}`);
  seenSlugs.add(c.slug);
}
const seenRules = new Set();
const grammarRules = concat('grammarRules');
for (const r of grammarRules) {
  if (seenRules.has(r.code)) throw new Error(`Duplicate grammar rule code in seed data: ${r.code}`);
  seenRules.add(r.code);
}

module.exports = {
  categories,
  grammarRules,
  words: concat('words'),
  grammarExercises: concat('grammarExercises'),
  practicalSentences: concat('practicalSentences'),
  readings: concat('readings'),
  // per-level drill configuration (which categories/rules the generated
  // conjugation/declension drills go into), see levels/<level>.js `drills`
  drills: levelModules.map((m, i) => (m.drills ? { level: LEVEL_ORDER[i].toUpperCase(), ...m.drills } : null)).filter(Boolean),
  forms
};
